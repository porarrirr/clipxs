import AppKit
import Foundation

struct CapturedClipboardItem {
    let entry: ClipboardEntry
    let contentHash: String
    /// PNG data for image entries. Written to `entry.payload` by ClipboardStore
    /// on its serial queue, so file creation cannot race the orphan cleanup.
    let imageData: Data?

    init(entry: ClipboardEntry, contentHash: String, imageData: Data? = nil) {
        self.entry = entry
        self.contentHash = contentHash
        self.imageData = imageData
    }
}

enum PasteboardCapture {
    private static let previewLimit = 200
    private static let maxRichPayloadBytes = 1_000_000

    /// Standard markers (http://nspasteboard.org) set by password managers and
    /// other apps whose copies must never be recorded.
    private static let excludedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    static func capture(
        from pasteboard: NSPasteboard = .general,
        sourceBundleId: String? = nil
    ) -> CapturedClipboardItem? {
        if pasteboard.types?.contains(where: { excludedTypes.contains($0.rawValue) }) == true {
            return nil
        }
        if let files = readFileURLs(from: pasteboard), !files.isEmpty {
            return makeFilesItem(urls: files, sourceBundleId: sourceBundleId)
        }
        if let imageItem = makeImageItem(from: pasteboard, sourceBundleId: sourceBundleId) {
            return imageItem
        }
        if let textItem = makeTextItem(from: pasteboard, sourceBundleId: sourceBundleId) {
            return textItem
        }
        return nil
    }

    /// Single-line preview derivation, shared with in-panel editing so edited
    /// entries look the same as freshly captured ones.
    static func textPreview(from text: String) -> String {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return String(trimmed.prefix(previewLimit))
            .replacingOccurrences(of: "\n", with: " ")
    }

    private static func readFileURLs(from pasteboard: NSPasteboard) -> [URL]? {
        guard pasteboard.canReadObject(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) else {
            return nil
        }
        let objects = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [NSURL]
        let urls = objects?.compactMap { $0 as URL }.filter { $0.isFileURL } ?? []
        return urls.isEmpty ? nil : urls
    }

    private static func makeFilesItem(urls: [URL], sourceBundleId: String?) -> CapturedClipboardItem {
        let paths = urls.map(\.path)
        let payloadData = try? JSONEncoder().encode(paths)
        let payload = String(data: payloadData ?? Data(), encoding: .utf8) ?? "[]"
        let hash = ContentHash.sha256(payload)

        let firstName = urls.first?.lastPathComponent ?? ""
        let preview: String
        if urls.count == 1 {
            preview = firstName
        } else {
            preview = String(
                format: NSLocalizedString("files_preview_multiple", comment: ""),
                urls.count,
                firstName
            )
        }

        let entry = ClipboardEntry(type: .files, preview: preview, payload: payload, sourceBundleId: sourceBundleId)
        return CapturedClipboardItem(entry: entry, contentHash: hash)
    }

    private static func makeImageItem(from pasteboard: NSPasteboard, sourceBundleId: String?) -> CapturedClipboardItem? {
        let pngData: Data?
        if let image = pasteboard.readObjects(forClasses: [NSImage.self])?.first as? NSImage,
           let tiff = image.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff) {
            pngData = rep.representation(using: .png, properties: [:])
        } else if let data = pasteboard.data(forType: .png) {
            pngData = data
        } else if let data = pasteboard.data(forType: .tiff),
                  let rep = NSBitmapImageRep(data: data) {
            pngData = rep.representation(using: .png, properties: [:])
        } else {
            pngData = nil
        }

        guard let png = pngData else { return nil }

        let fileName = UUID().uuidString + ".png"
        let fileURL = ClipboardStore.shared.imagesDirectory.appendingPathComponent(fileName)
        let hash = ContentHash.sha256(png)
        let preview = NSLocalizedString("image_preview", comment: "")
        let entry = ClipboardEntry(type: .image, preview: preview, payload: fileURL.path, sourceBundleId: sourceBundleId)
        return CapturedClipboardItem(entry: entry, contentHash: hash, imageData: png)
    }

    private static func makeTextItem(from pasteboard: NSPasteboard, sourceBundleId: String?) -> CapturedClipboardItem? {
        guard let text = pasteboard.string(forType: .string) else { return nil }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }

        let preview = textPreview(from: text)
        // Hash the plain string only, so rich and plain copies of the same
        // text still dedup against each other.
        let hash = ContentHash.sha256(text)

        var richPayload: Data?
        var richFormat: RichTextFormat?
        if let rtf = pasteboard.data(forType: .rtf), rtf.count <= maxRichPayloadBytes {
            richPayload = rtf
            richFormat = .rtf
        } else if let html = pasteboard.data(forType: .html), html.count <= maxRichPayloadBytes {
            richPayload = html
            richFormat = .html
        }

        let entry = ClipboardEntry(
            type: .text,
            preview: preview,
            payload: text,
            richPayload: richPayload,
            richFormat: richFormat,
            sourceBundleId: sourceBundleId
        )
        return CapturedClipboardItem(entry: entry, contentHash: hash)
    }
}
